-- Versiona o que existia só no banco de produção: perfis_admin, is_admin(),
-- visitas_perfil (com origem, campanha e sessao_id) e as chaves estrangeiras
-- do rastreio (cliques, rastreio_amostra, visitas_perfil).
--
-- Conferido em 28/10/2026 no banco de produção (information_schema,
-- pg_constraint, pg_policies, pg_class e pg_indexes, mais a definição de
-- is_admin() em pg_proc). Idempotente: em produção não altera nada; em um
-- ambiente novo cria o que falta.
--
-- Limite conhecido: a base do schema (prestadores, profiles etc.) ainda não
-- está nas migrations (remote_schema.sql está vazio). Por isso tudo o que
-- depende de public.prestadores é criado só se a tabela existir.
--
-- Esta migration mantém a policy "Qualquer um pode registrar visita" porque
-- ela ainda reflete produção; a remoção entra junto com a gravação de
-- visitas pelo servidor (tarefa 3b), depois do deploy.

-- ── perfis_admin ────────────────────────────────────────────────────────
create table if not exists public.perfis_admin (
  user_id    uuid        not null,
  email      text        not null,
  role       text        default 'editor',
  created_at timestamptz default now(),
  constraint perfis_admin_pkey primary key (user_id),
  constraint perfis_admin_role_check
    check (role = any (array['owner'::text, 'moderator'::text, 'editor'::text])),
  constraint perfis_admin_user_id_fkey
    foreign key (user_id) references auth.users (id)
);

alter table public.perfis_admin enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'perfis_admin'
      and policyname = 'admin_pode_ler_propria_linha'
  ) then
    create policy admin_pode_ler_propria_linha
      on public.perfis_admin for select to public
      using (user_id = auth.uid());
  end if;
end $$;

-- ── is_admin() ──────────────────────────────────────────────────────────
-- Mesma definição de produção. Precisa vir depois de perfis_admin, porque
-- funções em SQL são validadas na criação.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path to ''
as $function$
  select exists (
    select 1 from public.perfis_admin where user_id = (select auth.uid())
  );
$function$;

-- ── visitas_perfil ──────────────────────────────────────────────────────
-- A chave estrangeira para prestadores é adicionada mais abaixo, só se a
-- tabela prestadores existir.
create table if not exists public.visitas_perfil (
  id           bigint      generated by default as identity,
  prestador_id bigint      not null,
  criado_em    timestamptz not null default now(),
  origem       text,
  campanha     text,
  sessao_id    text,
  constraint visitas_perfil_pkey primary key (id),
  constraint visitas_perfil_origem_check    check (char_length(origem)    <= 60),
  constraint visitas_perfil_campanha_check  check (char_length(campanha)  <= 100),
  constraint visitas_perfil_sessao_id_check check (char_length(sessao_id) <= 64)
);

-- Índices de produção que ficam. O índice idx_visitas_perfil_prestador_data
-- (prestador_id, criado_em crescente) é redundante com o primeiro abaixo e
-- é removido na migration seguinte; por isso não é criado aqui.
create index if not exists idx_visitas_prestador_data
  on public.visitas_perfil (prestador_id, criado_em desc);
create index if not exists idx_visitas_origem_data
  on public.visitas_perfil (origem, criado_em desc);

alter table public.visitas_perfil enable row level security;

-- ── Policies ────────────────────────────────────────────────────────────
do $$
begin
  -- Prestador vê só as próprias visitas (depende de prestadores)
  if to_regclass('public.prestadores') is not null
     and not exists (
       select 1 from pg_policies
       where schemaname = 'public' and tablename = 'visitas_perfil'
         and policyname = 'Prestador vê apenas suas próprias visitas'
     ) then
    create policy "Prestador vê apenas suas próprias visitas"
      on public.visitas_perfil for select to authenticated
      using (exists (
        select 1 from public.prestadores
        where prestadores.id = visitas_perfil.prestador_id
          and prestadores.user_id = auth.uid()
      ));
  end if;

  -- Admin lê todas as visitas
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'visitas_perfil'
      and policyname = 'Admin lê todas as visitas'
  ) then
    create policy "Admin lê todas as visitas"
      on public.visitas_perfil for select to authenticated
      using (public.is_admin());
  end if;

  -- Estado atual de produção: qualquer pessoa insere visita pela API pública.
  -- Sai na tarefa 3b (gravação pelo servidor), depois do deploy.
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'visitas_perfil'
      and policyname = 'Qualquer um pode registrar visita'
  ) then
    create policy "Qualquer um pode registrar visita"
      on public.visitas_perfil for insert to anon, authenticated
      with check (true);
  end if;

  -- A migration de cliques (20261025114000) roda antes desta e só cria a
  -- policy do admin se is_admin() já existir. Em ambiente novo ela é pulada,
  -- então fica garantida aqui.
  if to_regclass('public.cliques') is not null
     and not exists (
       select 1 from pg_policies
       where schemaname = 'public' and tablename = 'cliques'
         and policyname = 'Admin lê todos os cliques'
     ) then
    create policy "Admin lê todos os cliques"
      on public.cliques for select to authenticated
      using (public.is_admin());
  end if;
end $$;

-- ── Chaves estrangeiras para prestadores (ON DELETE CASCADE) ────────────
-- Conferidas em produção em 28/10/2026. Só cria se ainda não houver nenhuma
-- FK da tabela para prestadores, para não duplicar com outro nome.
do $$
declare
  t text;
begin
  if to_regclass('public.prestadores') is null then
    raise notice 'public.prestadores não existe: FKs do rastreio puladas.';
    return;
  end if;

  foreach t in array array['cliques', 'rastreio_amostra', 'visitas_perfil'] loop
    -- Dois IFs de propósito: o Postgres não garante o curto-circuito do AND, e o
    -- cast ::regclass dá erro quando a tabela não existe.
    if to_regclass('public.' || t) is null then
      raise notice 'public.% não existe: FK para prestadores pulada.', t;
      continue;
    end if;

    if not exists (
         select 1 from pg_constraint c
         where c.conrelid = ('public.' || t)::regclass
           and c.contype = 'f'
           and c.confrelid = 'public.prestadores'::regclass
       ) then
      execute format(
        'alter table public.%I add constraint %I foreign key (prestador_id) '
        'references public.prestadores (id) on delete cascade',
        t, t || '_prestador_id_fkey'
      );
    end if;
  end loop;
end $$;
