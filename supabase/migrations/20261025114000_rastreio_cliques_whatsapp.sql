-- Versiona as tabelas do rastreio de cliques no WhatsApp (Tarefas 3 e 4).
--
-- Estas tabelas já existem no banco de produção, criadas à mão fora do
-- repositório. Esta migration só registra o estado conhecido, de forma
-- idempotente: em produção não altera nada; em um ambiente novo
-- (homologação, banco local) cria o que falta.
--
-- Estrutura conferida em 25/10/2026 (information_schema e pg_policies).
-- Ainda NÃO conferidos: chaves primárias, chaves estrangeiras e índices
-- (o resultado da consulta de índices não foi coletado). As chaves
-- primárias abaixo são as esperadas pelo código (consulta por id/chave),
-- e valem apenas para ambientes novos.

-- ── cliques ─────────────────────────────────────────────────────────────
create table if not exists public.cliques (
  id           bigint generated by default as identity primary key,
  prestador_id bigint,
  created_at   timestamptz default now(),
  origem       text,
  campanha     text,
  sessao_id    text
);

-- ── rastreio_config: modo do rastreio ('amostra' | 'todos') ─────────────
create table if not exists public.rastreio_config (
  chave         text primary key,
  valor         text not null,
  atualizado_em timestamptz not null default now()
);

-- ── rastreio_amostra: prestadores incluídos no teste por amostra ────────
create table if not exists public.rastreio_amostra (
  prestador_id bigint primary key,
  observacao   text,
  criado_em    timestamptz not null default now()
);

-- Valor inicial seguro: o código já trata qualquer valor diferente de
-- 'todos' como 'amostra'. Não sobrescreve o que já existe.
insert into public.rastreio_config (chave, valor)
select 'modo', 'amostra'
where not exists (select 1 from public.rastreio_config where chave = 'modo');

-- ── RLS ─────────────────────────────────────────────────────────────────
-- A rota /api/prestadores/clique-whatsapp usa o cliente administrativo
-- (service role), que ignora o RLS. As tabelas do rastreio não precisam
-- de política para o navegador.
alter table public.cliques          enable row level security;
alter table public.rastreio_config  enable row level security;
alter table public.rastreio_amostra enable row level security;

do $$
begin
  -- Admin lê todos os cliques (depende de is_admin(), criada fora das migrations)
  if to_regprocedure('public.is_admin()') is not null
     and not exists (
       select 1 from pg_policies
       where schemaname = 'public' and tablename = 'cliques'
         and policyname = 'Admin lê todos os cliques'
     ) then
    create policy "Admin lê todos os cliques"
      on public.cliques for select to authenticated
      using (public.is_admin());
  end if;

  -- Prestador vê só os próprios cliques (depende da tabela prestadores)
  if to_regclass('public.prestadores') is not null
     and not exists (
       select 1 from pg_policies
       where schemaname = 'public' and tablename = 'cliques'
         and policyname = 'Prestador vê apenas seus próprios cliques'
     ) then
    create policy "Prestador vê apenas seus próprios cliques"
      on public.cliques for select to authenticated
      using (exists (
        select 1 from public.prestadores p
        where p.id = cliques.prestador_id
          and p.user_id = (select auth.uid())
      ));
  end if;

  -- ATENÇÃO: política existente em produção que deixa QUALQUER pessoa
  -- inserir cliques direto pela API pública do Supabase, sem passar pelas
  -- regras da rota (robôs, dedupe 24h, amostra). Mantida aqui só para
  -- refletir o estado atual; a remoção está proposta como passo próprio
  -- (ver documentacao/docs/14-melhorias-plataforma-cliques-whatsapp.md).
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'cliques'
      and policyname = 'Qualquer um pode registrar um clique'
  ) then
    create policy "Qualquer um pode registrar um clique"
      on public.cliques for insert to public
      with check (true);
  end if;
end $$;
